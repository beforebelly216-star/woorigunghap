const DAYS_BEFORE_MONTH = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334] as const;

function getCalendarParts(date: Date, timeZone: string) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    month: "numeric",
    day: "numeric",
  }).formatToParts(date);

  return {
    month: Number(parts.find((part) => part.type === "month")?.value),
    day: Number(parts.find((part) => part.type === "day")?.value),
  };
}

export function getDailyQuoteIndex(date: Date, timeZone = "Asia/Seoul") {
  const { month, day } = getCalendarParts(date, timeZone);
  const normalizedDay = month === 2 && day === 29 ? 28 : day;
  return DAYS_BEFORE_MONTH[month - 1] + normalizedDay - 1;
}

export function getDailyQuote(date: Date, timeZone = "Asia/Seoul") {
  return DAILY_QUOTES[getDailyQuoteIndex(date, timeZone)];
}
