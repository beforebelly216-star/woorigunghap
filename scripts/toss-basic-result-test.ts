import assert from "node:assert/strict";
import { writeFileSync,readFileSync } from "node:fs";
import { calculateTossBasicResult,TOSS_BASIC_SAMPLE_INPUT,TossBasicInputError } from "../src/lib/toss-basic-result";
import { calculateOneToOneCompatibility } from "../src/lib/compatibility/engine";
import { parseOneToOneReportInput } from "../src/lib/report-input";
import { validateBasicResult,basicInput,calculateBasic } from "../apps/toss/src/basic-client.js";
import { NextRequest } from "next/server";
import { createTossBasicHandler } from "../src/lib/toss-basic-handler";

async function main() {
  const result=calculateTossBasicResult(TOSS_BASIC_SAMPLE_INPUT);
  const snapshot=calculateOneToOneCompatibility(parseOneToOneReportInput(TOSS_BASIC_SAMPLE_INPUT)!);
  assert.equal(result.score,snapshot.score);
  assert.equal(result.scoreRange.min,snapshot.uncertaintyRange.min);
  assert.equal(result.scoreRange.max,snapshot.uncertaintyRange.max);
  assert.equal(validateBasicResult(result),result);
  const dto=JSON.stringify(result);
  for (const name of ['birthDate','birthTime','representativeEvidence','paymentId','providerUserId']) assert.equal(dto.includes(name),false);
  assert.equal(dto.includes(TOSS_BASIC_SAMPLE_INPUT.personA.birthDate),false);
  assert.throws(()=>calculateTossBasicResult(null),TossBasicInputError);
  assert.throws(()=>calculateTossBasicResult({...TOSS_BASIC_SAMPLE_INPUT,personA:{...TOSS_BASIC_SAMPLE_INPUT.personA,birthDate:'1990-02-30'}}),TossBasicInputError);
  assert.throws(()=>calculateTossBasicResult({...TOSS_BASIC_SAMPLE_INPUT,relationshipType:'coworker'}),TossBasicInputError);
  assert.equal(calculateTossBasicResult({...TOSS_BASIC_SAMPLE_INPUT,relationshipType:'coworker',coworkerHierarchy:'peer'}).relationshipType,'coworker');
  const unknown=calculateTossBasicResult({...TOSS_BASIC_SAMPLE_INPUT,personA:{...TOSS_BASIC_SAMPLE_INPUT.personA,birthTimeKnown:false,birthTime:null}});
  assert.equal(unknown.timeUnknown,true); validateBasicResult(unknown);
  assert.throws(()=>validateBasicResult({...result,score:101}));
  assert.throws(()=>validateBasicResult({...result,grade:'wrong'}));
  assert.throws(()=>validateBasicResult({...result,dimensions:[result.dimensions[0],result.dimensions[0]]}));
  const draft={relationship:'친구',self:{name:' 하늘 ',gender:'male',calendar:'solar',date:'1990-05-15',time:'',unknownTime:true,leapMonth:true},partner:{name:'바다',gender:'female',calendar:'lunar',date:'1992-10-24',time:'05:30',unknownTime:false,leapMonth:true}};
  const mapped=basicInput(draft);
  assert.equal(mapped.personA.birthTime,null);assert.equal(mapped.personA.isLeapMonth,false);assert.equal(mapped.personA.displayName,'하늘');
  assert.equal(mapped.personB.isLeapMonth,true);assert.equal(mapped.relationshipType,'friend');
  let calls=0;
  const fake={request:async (path:string,options:{body:string})=>{calls++;assert.equal(path,'/api/toss/compatibility');const body=JSON.parse(options.body);assert.equal(body.partnerConsent,true);assert.equal(body.input.relationshipType,'friend');return {result};}};
  await assert.rejects(calculateBasic(fake,draft,false,undefined));assert.equal(calls,0);
  assert.equal(await calculateBasic(fake,draft,true,undefined),result);assert.equal(calls,1);
  const origin='https://woorisajoo.apps.tossmini.com';
  const request=(body:unknown,requestOrigin=origin)=>new NextRequest('https://server.example/api/toss/compatibility',{method:'POST',headers:{origin:requestOrigin},body:JSON.stringify(body)});
  const deps={authenticate:async()=>({provider:'toss'}),allowedOrigin:(value:string|null)=>value===origin,enabled:()=>true};
  const handler=createTossBasicHandler(deps);
  const success=await handler(request({input:TOSS_BASIC_SAMPLE_INPUT,partnerConsent:true}));
  assert.equal(success.status,200);assert.deepEqual((await success.json()).result,result);
  assert.equal(success.headers.get('cache-control'),'private, no-store');
  assert.equal((await handler(request({input:TOSS_BASIC_SAMPLE_INPUT,partnerConsent:false}))).status,400);
  assert.equal((await handler(request({input:TOSS_BASIC_SAMPLE_INPUT,partnerConsent:true},'https://evil.example'))).status,403);
  assert.equal((await createTossBasicHandler({...deps,authenticate:async()=>null})(request({}))).status,401);
  assert.equal((await createTossBasicHandler({...deps,authenticate:async()=>({provider:'kakao'})})(request({}))).status,401);
  assert.equal((await createTossBasicHandler({...deps,enabled:()=>false})(request({}))).status,503);
  const invalid=await handler(request({input:null,partnerConsent:true}));assert.equal(invalid.status,400);assert.ok((await invalid.json()).fieldErrors.input);
  assert.equal((await handler(request({input:'x'.repeat(17000),partnerConsent:true}))).status,400);
  const path='apps/toss/src/basic-sample.json';
  if (process.argv.includes('--write-sample')) writeFileSync(path,JSON.stringify(result,null,2)+'\n');
  assert.deepEqual(JSON.parse(readFileSync(path,'utf8')),result);
  console.log('Toss free calculation: actual engine/grade/range, DTO privacy, invalid/unknown/coworker inputs, client, handler auth/Origin/OFF/consent/body limit, bundled sample PASS');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
